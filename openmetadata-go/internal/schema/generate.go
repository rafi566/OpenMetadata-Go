type GenerateOptions struct{ Package, OutputDir string }
type modelIndexEntry struct {
	Path    string `json:"path"`
	Pointer string `json:"pointer"`
	Name    string `json:"name"`
	SHA256  string `json:"sha256"`
}
type registryManifestEntry struct {
	Path   string `json:"path"`
	SHA256 string `json:"sha256"`
}
type modelGenerator struct {
	registry *Registry
	names    map[string]string
	symbols  map[string]string
	optional string
}

// Generate emits only a supported, checked graph. All identities and raw sources
// remain bound to their original path/pointer; no display-title deduplication occurs.
// ADR:2026-10-17-go-schema-reconstruction-preserves-source-semantics
func Generate(r *Registry, o GenerateOptions) ([]string, error) {
	if r == nil {
		return nil, errors.New("nil registry")
	}
	if !token.IsIdentifier(o.Package) || token.Lookup(o.Package).IsKeyword() || o.Package == "_" || o.OutputDir == "" {
		return nil, errors.New("generation requires valid package and output directory")
	}
	g := modelGenerator{registry: r, names: map[string]string{}, symbols: map[string]string{}, optional: "presence."}
	// Identify the target module, rather than a build-time source directory that
	// may disappear or become relative under -trimpath.
	outAbs, e := filepath.Abs(o.OutputDir)
	if e != nil {
		return nil, e
	}
	if e = outputAncestors(outAbs); e != nil {
		return nil, e
	}
	for _, path := range sortedKeys(r.documents) {
		if e := embeddedSourcePath(path); e != nil {
			return nil, diagnostic("generate", path, "", e)
		}
	}
	if localOptionalPackage(outAbs) {
		if o.Package != "schema" {
			return nil, errors.New("support output directory requires package schema")
		}
		g.optional = ""
	}
	files := map[string][]byte{}
	fileOwners := map[string]string{}
	var index []modelIndexEntry
	for _, n := range r.Nodes() {
		entry := r.schemas[keyAt(n.Path, n.Pointer)]
		if e := g.supported(entry); e != nil {
			return nil, e
		}
		name, e := GoName(n)
		if e != nil {
			return nil, e
		}
		if e = g.claim(name, n.Path+"#"+n.Pointer); e != nil {
			return nil, e
		}
		g.names[keyOf(entry)] = name
		filename := "models_" + strings.ToLower(name) + ".go"
		fold := filenameFold(filename)
		if old, ok := fileOwners[fold]; ok {
			return nil, diagnostic("generate", n.Path, n.Pointer, fmt.Errorf("case-insensitive filename collision %s (also %s)", filename, old))
		}
		fileOwners[fold] = n.Path + "#" + n.Pointer
		if len(filename) > 240 {
			return nil, diagnostic("generate", n.Path, n.Pointer, fmt.Errorf("generated filename exceeds 240 bytes"))
		}
		index = append(index, modelIndexEntry{n.Path, n.Pointer, name, fmt.Sprintf("%x", sha256.Sum256(r.documents[n.Path].Document))})
	}
	// Check unused nodes too, before producing even one output file.
	if _, e = r.Check(); e != nil {
		return nil, e
	}
	for _, n := range r.Nodes() {
		b, e := g.model(r.schemas[keyAt(n.Path, n.Pointer)], o.Package)
		if e != nil {
			return nil, e
		}
		files["models_"+strings.ToLower(g.names[keyAt(n.Path, n.Pointer)])+".go"] = b
	}
	profile := ""
	if r.legacy {
		profile = LegacyProfile
	}
	registrySource := fmt.Sprintf(`// SPDX-License-Identifier: Apache-2.0
// Code generated by om-contracts schema generate; DO NOT EDIT.
package %s
import("embed";"errors";"io/fs";"sync"; "github.com/santhosh-tekuri/jsonschema/v6"; support "github.com/rafi566/OpenMetadata-Go/openmetadata-go/internal/schema")
//go:embed all:registry
var modelSchemas embed.FS
var modelRegistry = sync.OnceValues(func()(*support.Registry,error){source,e:=fs.Sub(modelSchemas,"registry");if e!=nil{return nil,e};return support.LoadEmbeddedRegistry(source,%q)})
func modelDecode(id string,b []byte)(support.Value,error){r,e:=modelRegistry();if e!=nil{return support.Value{},e};if e=r.Validate(id,b);e!=nil{return support.Value{},e};return support.ParseValue(b)}
func modelValidate(id string,v support.Value)error{b,e:=v.MarshalJSON();if e!=nil{return e};r,e:=modelRegistry();if e!=nil{return e};return r.Validate(id,b)}
func modelBranch(id string,v support.Value)(support.Value,bool,error){if e:=modelValidate(id,v);e!=nil{var d *support.Diagnostic;if errors.As(e,&d)&&d.Stage=="validate"{if _,invalid:=d.Cause.(*jsonschema.ValidationError);invalid{return support.Value{},false,nil}};return support.Value{},false,e};return v,true,nil}
`, o.Package, profile)
	files["models_registry.go"], e = goSource(registrySource)
	if e != nil {
		return nil, e
	}
	files["model-index.json"], e = json.MarshalIndent(index, "", "  ")
	if e != nil {
		return nil, e
	}
	files["model-index.json"] = append(files["model-index.json"], '\n')
	var manifest []registryManifestEntry
	for _, p := range sortedKeys(r.documents) {
		raw := r.documents[p].Document
		files["registry/"+p] = bytes.Clone(raw)
		manifest = append(manifest, registryManifestEntry{p, fmt.Sprintf("%x", sha256.Sum256(raw))})
	}
	files["registry-manifest.json"], e = json.MarshalIndent(manifest, "", "  ")
	if e != nil {
		return nil, e
	}
	files["registry-manifest.json"] = append(files["registry-manifest.json"], '\n')
	return writeGeneratedFiles(outAbs, files)
}

// Go rejects filename pairs using Unicode simple-fold equivalence, which is
// broader than lowercasing (for example, s and ſ). Canonicalize each finite
// fold orbit once per rune instead of comparing every pair of filenames.
func filenameFold(name string) string {
	var folded strings.Builder
	folded.Grow(len(name))
	for _, r := range name {
		for {
			next := unicode.SimpleFold(r)
			if next <= r {
				r = next
				break
			}
			r = next
		}
		folded.WriteRune(r)
	}
	return folded.String()
}

// Go 1.27.2's cmd/go/internal/load.isBadEmbedName applies module.CheckFilePath
// to each component and excludes VCS directories, even under all:registry.
// Keep this preflight aligned with that selected toolchain without renaming or
// dropping raw sources, or importing cmd/go's private implementation.
func embeddedSourcePath(path string) error {
	components := strings.Split(path, "/")
	for i, name := range components {
		// Go's embedding walk treats any child named go.mod as a module
		// boundary, including a directory, and can skip the parent's subtree.
		if i < len(components)-1 && name == "go.mod" {
			return fmt.Errorf("%w: source directory %q creates a Go embedding module boundary", ErrBlocked, name)
		}
		if err := embeddedSourceComponent(name); err != nil {
			return fmt.Errorf("%w: source component %q cannot be embedded: %v", ErrBlocked, name, err)
		}
	}
	return nil
}

func embeddedSourceComponent(name string) error {
	if !utf8.ValidString(name) || name == "" || strings.HasSuffix(name, ".") {
		return errors.New("invalid UTF-8, empty name, or trailing dot")
	}
	switch name {
	case ".bzr", ".hg", ".git", ".svn":
		return errors.New("version-control directory is excluded by Go embedding")
	}
	for _, r := range name {
		if r < utf8.RuneSelf {
			if r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || strings.ContainsRune("!#$%&()+,-.=@[]^_{}~ ", r) {
				continue
			}
		} else if unicode.IsLetter(r) {
			continue
		}
		return fmt.Errorf("character %q is not allowed in an embedded filename", r)
	}
	base, _, _ := strings.Cut(name, ".")
	for _, reserved := range [...]string{"CON", "PRN", "AUX", "NUL", "COM1", "COM2", "COM3", "COM4", "COM5", "COM6", "COM7", "COM8", "COM9", "LPT1", "LPT2", "LPT3", "LPT4", "LPT5", "LPT6", "LPT7", "LPT8", "LPT9"} {
		if strings.EqualFold(base, reserved) {
			return fmt.Errorf("base name %q is reserved on Windows", base)
		}
	}
	return nil
}

func preflightGeneratedFiles(outAbs string, files map[string][]byte) error {
	total := 0
	for _, p := range sortedKeys(files) {
		total += len(files[p])
		if total > 256<<20 {
			return errors.New("generated output exceeds 256 MiB")
		}
		if e := outputAncestors(filepath.Dir(filepath.Join(outAbs, filepath.FromSlash(p)))); e != nil {
			return e
		}
		if _, e := os.Lstat(filepath.Join(outAbs, filepath.FromSlash(p))); e == nil {
			return fmt.Errorf("output already exists: %s", p)
		} else if !os.IsNotExist(e) {
			return e
		}
	}
	return nil
}

func writeGeneratedFiles(outAbs string, files map[string][]byte) ([]string, error) {
	if err := preflightGeneratedFiles(outAbs, files); err != nil {
		return nil, err
	}
	var result []string
	for _, p := range sortedKeys(files) {
		dest := filepath.Join(outAbs, filepath.FromSlash(p))
		if e := os.MkdirAll(filepath.Dir(dest), 0755); e != nil {
			return nil, e
		}
		f, e := os.OpenFile(dest, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0644)
		if e != nil {
			return nil, e
		}
		_, writeErr := f.Write(files[p])
		closeErr := f.Close()
		if writeErr != nil {
			return nil, writeErr
		}
		if closeErr != nil {
			return nil, closeErr
		}
		result = append(result, p)
	}
	return result, nil
}

// Reject links at every existing ancestor before creating any output. Checking
// only the leaf lets a registry subdirectory or output root redirect writes.
func outputAncestors(dir string) error {
	for {
		info, err := os.Lstat(dir)
		if err == nil {
			if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
				return fmt.Errorf("output ancestor must be a physical directory: %s", dir)
			}
		} else if !os.IsNotExist(err) {
			return err
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return nil
		}
		dir = parent
	}
}
func (g *modelGenerator) claim(name, loc string) error {
	if old, ok := g.symbols[name]; ok {
		return fmt.Errorf("generate: final Go identifier %s collision: %s and %s", name, old, loc)
	}
	g.symbols[name] = loc
	return nil
}
func (g *modelGenerator) supported(n *entry) error {
	m, ok := n.value.(map[string]any)
	if !ok {
		return nil
	}
	if _, ref := m["$ref"]; ref && strings.Contains(g.registry.inheritedDialect(n), "draft-07") {
		return nil
	}
	dialect := g.registry.inheritedDialect(n)
	modern := !strings.Contains(dialect, "draft-07")
	latest := modern && !strings.Contains(dialect, "2019-09")
	for _, k := range []string{"patternProperties", "$dynamicRef", "$recursiveRef"} {
		if (k == "$dynamicRef" && !latest) || (k == "$recursiveRef" && (!modern || latest)) {
			continue
		}
		if _, ok := m[k]; ok {
			return diagnostic("generate", n.Path, n.Pointer+"/"+escape(k), fmt.Errorf("%w: %s projection is unsupported", ErrBlocked, k))
		}
	}
	return nil
}
func (g *modelGenerator) shape(n *entry) (*entry, error) {
	seen := map[string]bool{}
	for {
		if seen[keyOf(n)] {
			return nil, diagnostic("generate", n.Path, n.Pointer, fmt.Errorf("%w: pure reference cycle has no typed shape", ErrBlocked))
		}
		seen[keyOf(n)] = true
		m, ok := n.value.(map[string]any)
		if !ok {
			return n, nil
		}
		ref, ok := m["$ref"].(string)
		if !ok || (!strings.Contains(g.registry.inheritedDialect(n), "draft-07") && localProjection(m)) {
			return n, nil
		}
		next, e := g.registry.resolve(n.base, ref)
		if e != nil {
			return nil, e
		}
		n = next
	}
}
func (g *modelGenerator) model(n *entry, pkg string) ([]byte, error) {
	name := g.names[keyOf(n)]
	shape, e := g.shape(n)
	if e != nil {
		return nil, e
	}
	m, _ := shape.value.(map[string]any)
	imports := map[string]string{"support": "github.com/rafi566/OpenMetadata-Go/openmetadata-go/internal/schema"}
	var body strings.Builder
	id := g.nodeID(n)
	fmt.Fprintf(&body, `type %s struct{ value support.Value }
func(v *%s) UnmarshalJSON(b []byte)error{next,e:=modelDecode(%q,b);if e!=nil{return e};v.value=next;return nil}
func(v %s) MarshalJSON()([]byte,error){return v.value.MarshalJSON()}
func(v %s) Validate()error{return modelValidate(%q,v.value)}
func(v %s) JSONValue() support.Value{return v.value}
`, name, name, id, name, name, id, name)
	if e := g.compositionViews(&body, name, shape); e != nil {
		return nil, e
	}
	types := projectionTypes(m)
	if types["string"] {
		fmt.Fprintf(&body, "func(v %s) StringValue()(string,bool){return v.value.StringValue()}\n", name)
	}
	if types["boolean"] {
		fmt.Fprintf(&body, "func(v %s) BoolValue()(bool,bool){return v.value.BoolValue()}\n", name)
	}
	if types["number"] || types["integer"] {
		fmt.Fprintf(&body, "func(v %s) NumberValue()(support.Number,bool){return v.value.NumberValue()}\n", name)
	}
	if enums, ok := m["enum"].([]any); ok {
		for i, v := range enums {
			if s, ok := v.(string); ok {
				constant := name + "Enum" + identifier(s)
				if e := g.claim(constant, n.Path+"#"+n.Pointer+"/enum/"+strconv.Itoa(i)); e != nil {
					return nil, e
				}
				fmt.Fprintf(&body, "const %s = %q\n", constant, s)
			}
		}
	}
	props, hasProps := m["properties"].(map[string]any)
	_, hasMap := m["additionalProperties"].(map[string]any)
	if types["object"] || hasProps || hasMap {
		projection := name + "Object"
		if e := g.claim(projection, n.Path+"#"+n.Pointer+" (object view)"); e != nil {
			return nil, e
		}
		fmt.Fprintf(&body, "// %s is a detached read projection. Serialize %s to retain unknown members.\ntype %s struct{\n", projection, name, projection)
		fields := map[string]string{}
		for _, key := range sortedKeys(props) {
			if !jsonFieldTagName(key) {
				return nil, diagnostic("generate", shape.Path, shape.Pointer+"/properties/"+escape(key), fmt.Errorf("%w: property name cannot be represented exactly by a Go JSON field tag", ErrBlocked))
			}
			field := identifier(key)
			loc := shape.Path + "#" + shape.Pointer + "/properties/" + escape(key)
			if old, ok := fields[field]; ok {
				return nil, fmt.Errorf("generate: field collision %s: %s and %s", field, old, loc)
			}
			fields[field] = loc
			child := g.names[keyAt(shape.Path, shape.Pointer+"/properties/"+escape(key))]
			if child == "" {
				return nil, fmt.Errorf("missing child schema %s", loc)
			}
			if g.optional != "" {
				imports["presence"] = "github.com/rafi566/OpenMetadata-Go/openmetadata-go/schema"
			}
			fmt.Fprintf(&body, "%s %sOptional[*%s] %s\n", field, g.optional, child, strconv.Quote("json:"+strconv.Quote(key+",omitzero")))
		}
		fmt.Fprint(&body, "}\n")
		fmt.Fprintf(&body, "func(v %s) Object()(%s,bool,error){var out %s;values,ok:=v.value.Object();if !ok{return out,false,nil};_ = values\n", name, projection, projection)
		for _, key := range sortedKeys(props) {
			if !jsonFieldTagName(key) {
				return nil, diagnostic("generate", shape.Path, shape.Pointer+"/properties/"+escape(key), fmt.Errorf("%w: property name cannot be represented exactly by a Go JSON field tag", ErrBlocked))
			}
			field := identifier(key)
			child := g.names[keyAt(shape.Path, shape.Pointer+"/properties/"+escape(key))]
			fmt.Fprintf(&body, "if raw,exists:=values[%q];exists{if raw.IsNull(){out.%s=%sNull[*%s]()}else{var child %s;if e:=child.UnmarshalJSON(raw.RawJSON());e!=nil{return %s{},false,e};out.%s=%sSome(&child)}}\n", key, field, g.optional, child, child, projection, field, g.optional)
		}
		fmt.Fprint(&body, "return out,true,nil}\n")
		if hasMap {
			child := g.names[keyAt(shape.Path, shape.Pointer+"/additionalProperties")]
			if child != "" && m["additionalProperties"] != false {
				fmt.Fprintln(&body, "// AdditionalProperties returns detached checked values for additional keys; false means a nonobject, and an empty object yields a nonnil empty map.")
				fmt.Fprintf(&body, "func(v %s) AdditionalProperties()(map[string]*%s,bool,error){if e:=v.Validate();e!=nil{return nil,false,e};values,ok:=v.value.Object();if !ok{return nil,false,nil};out:=make(map[string]*%s);for key,raw:=range values{\n", name, child, child)
				if len(props) > 0 {
					fmt.Fprint(&body, "switch key{case ")
					for i, key := range sortedKeys(props) {
						if i > 0 {
							fmt.Fprint(&body, ",")
						}
						fmt.Fprintf(&body, "%q", key)
					}
					fmt.Fprint(&body, ":continue}\n")
				}
				fmt.Fprintf(&body, "var child %s;if e:=child.UnmarshalJSON(raw.RawJSON());e!=nil{return nil,false,e};out[key]=&child};return out,true,nil}\n", child)
			}
		}
	}
	if types["array"] && !hasTuplePrefix(m, g.registry.inheritedDialect(shape)) {
		child := g.names[keyAt(shape.Path, shape.Pointer+"/items")]
		if child != "" {
			fmt.Fprintf(&body, "func(v %s) Items()([]*%s,bool,error){values,ok:=v.value.Array();if !ok{return nil,false,nil};out:=make([]*%s,len(values));for i,raw:=range values{var child %s;if e:=child.UnmarshalJSON(raw.RawJSON());e!=nil{return nil,false,e};out[i]=&child};return out,true,nil}\n", name, child, child, child)
		}
	}
	var source strings.Builder
	fmt.Fprintf(&source, "// SPDX-License-Identifier: Apache-2.0\n// Code generated by om-contracts schema generate; DO NOT EDIT.\npackage %s\nimport(\n", pkg)
	for _, alias := range sortedKeys(imports) {
		fmt.Fprintf(&source, "%s %q\n", alias, imports[alias])
	}
	fmt.Fprint(&source, ")\n", body.String())
	return goSource(source.String())
}
func goSource(source string) ([]byte, error) {
	set := token.NewFileSet()
	tree, e := parser.ParseFile(set, "generated.go", source, parser.ParseComments)
	if e != nil {
		return nil, e
	}
	var out bytes.Buffer
	if e = format.Node(&out, set, tree); e != nil {
		return nil, e
	}
	return out.Bytes(), nil
}

func (g *modelGenerator) nodeID(n *entry) string {
	if g.registry.legacy {
		return legacyBase + n.Path + fragment(n.Pointer)
	}
	return (&url.URL{Scheme: "file", Path: "/__openmetadata_embedded__/" + n.Path}).String() + fragment(n.Pointer)
}

func localOptionalPackage(output string) bool {
	for dir := output; ; dir = filepath.Dir(dir) {
		if raw, e := os.ReadFile(filepath.Join(dir, "go.mod")); e == nil {
			for _, line := range strings.Split(string(raw), "\n") {
				fields := strings.Fields(line)
				if len(fields) >= 2 && fields[0] == "module" {
					return strings.Trim(fields[1], "\"") == "github.com/rafi566/OpenMetadata-Go/openmetadata-go" && output == filepath.Join(dir, "schema")
				}
			}
			return false
		}
		if filepath.Dir(dir) == dir {
			return false
		}
	}
}
